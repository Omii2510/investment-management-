
require("dotenv").config();

const mongoose = require("mongoose");

const User = require("../models/User");
const Investment = require("../models/Investment");
const ReferralIncome = require("../models/ReferralIncome");
const ROIHistory = require("../models/ROIHistory");

async function testRelationships() {
  try {
    console.log("Starting database relationship tests...");

    // 1. Connect to MongoDB
    await mongoose.connect(process.env.MONGO_URI);
    console.log("MongoDB Connected Successfully!");

    // 2. Clean up previous test records
    console.log("\nCleaning previous test data...");

    const receiverEmail = "testuser@example.com";
    const generatedEmail = "generateduser@example.com";

    const existingUsers = await User.find({
      email: { $in: [receiverEmail, generatedEmail] }
    });

    const userIds = existingUsers.map(user => user._id);

    if (userIds.length > 0) {
      const existingInvestments = await Investment.find({
        user: { $in: userIds }
      }).select("_id");

      const investmentIds = existingInvestments.map(item => item._id);

      await ROIHistory.deleteMany({
        $or: [
          { user: { $in: userIds } },
          { investment: { $in: investmentIds } }
        ]
      });

      await Investment.deleteMany({ user: { $in: userIds } });

      await ReferralIncome.deleteMany({
        $or: [
          { receiver: { $in: userIds } },
          { generatedBy: { $in: userIds } }
        ]
      });

      await User.deleteMany({ _id: { $in: userIds } });
    }

    console.log("Previous test data cleaned!");

    // 3. Create receiver user
    console.log("\nCreating receiver user...");

    const receiver = await User.create({
      fullName: "Test Receiver",
      email: receiverEmail,
      mobileNumber: "9999999999",
      password: "TestPassword123",
      referralCode: "TESTUSER01"
    });

    console.log("Receiver created:", receiver.fullName);

    // 4. Create referred user
    console.log("\nCreating referred user...");

    const generatedBy = await User.create({
      fullName: "Test Referred User",
      email: generatedEmail,
      mobileNumber: "9999999998",
      password: "TestPassword123",
      referralCode: "TESTUSER02",
      referredBy: receiver._id
    });

    console.log("Referred user created:", generatedBy.fullName);

    // 5. Create investment
    console.log("\nCreating investment...");

    const investment = await Investment.create({
      user: receiver._id,
      investmentAmount: 10000,
      planDetails: {
        planName: "Test Plan",
        durationDays: 30,
        description: "Testing investment relationship"
      },
      startDate: new Date("2026-11-01T00:00:00.000Z"),
      endDate: new Date("2026-12-01T00:00:00.000Z"),
      dailyROIPercentage: 0.5
    });

    console.log("Investment created:", investment._id);

    // 6. Create referral income
    console.log("\nCreating referral income...");

    const referralIncome = await ReferralIncome.create({
      receiver: receiver._id,
      generatedBy: generatedBy._id,
      referralLevel: 1,
      incomeAmount: 100
    });

    console.log("Referral income created:", referralIncome._id);

    // 7. Create ROI history
    console.log("\nCreating ROI history...");

    const roiHistory = await ROIHistory.create({
      user: receiver._id,
      investment: investment._id,
      roiAmount: 50,
      date: new Date("2026-11-02T00:00:00.000Z"),
      status: "Credited"
    });

    console.log("ROI history created:", roiHistory._id);

    // 8. Verify relationships using populate()
    console.log("\nVerifying relationships...");

    const investmentData = await Investment.findById(investment._id)
      .populate("user", "fullName email");

    const referralData = await ReferralIncome.findById(referralIncome._id)
      .populate("receiver", "fullName")
      .populate("generatedBy", "fullName");

    const roiData = await ROIHistory.findById(roiHistory._id)
      .populate("user", "fullName")
      .populate("investment");

    const referredUserData = await User.findById(generatedBy._id)
      .populate("referredBy", "fullName");

    // 9. Display results
    console.log("\n========== RELATIONSHIP RESULTS ==========");

    console.log(
      "Investment belongs to:",
      investmentData.user.fullName
    );

    console.log(
      "Referral receiver:",
      referralData.receiver.fullName
    );

    console.log(
      "Referral generated by:",
      referralData.generatedBy.fullName
    );

    console.log(
      "Referred by:",
      referredUserData.referredBy.fullName
    );

    console.log(
      "ROI belongs to:",
      roiData.user.fullName
    );

    console.log(
      "ROI investment ID:",
      roiData.investment._id
    );

    console.log("\nALL RELATIONSHIP TESTS PASSED!");

  } catch (error) {
    console.error("\nTEST FAILED!");
    console.error(error.stack || error.message);

  } finally {
    if (mongoose.connection.readyState !== 0) {
      await mongoose.disconnect();
      console.log("\nMongoDB connection closed.");
    }
  }
}

testRelationships().catch(error => {
  console.error("Unexpected script error:", error);
  process.exitCode = 1;
});
